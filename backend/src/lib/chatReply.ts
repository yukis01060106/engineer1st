const DEFAULT_REPLY = "ご連絡ありがとうございます。内容を確認し、担当より1営業日以内に折り返しご連絡します。";

export function autoReply(text: string): string {
  const rule = RULES.find((r) => r.keywords.some((k) => text.includes(k)));
  return rule ? rule.reply : DEFAULT_REPLY;
}

